// Helper functions to query indicators and documents
function getStandardById(stdId) {
  return STANDARDS_DATA.find(s => s.id === parseInt(stdId));
}

function getAllSubIndicators() {
  const list = [];
  STANDARDS_DATA.forEach(std => {
    std.keyIndicators.forEach(keyInd => {
      keyInd.subIndicators.forEach(sub => {
        list.push({
          ...sub,
          standardId: std.id,
          standardTitle: std.title,
          standardColor: std.color,
          keyIndicatorTitle: keyInd.title
        });
      });
    });
  });
  return list;
}

function getSubIndicatorByCode(code) {
  const all = getAllSubIndicators();
  return all.find(item => item.code === code);
}
